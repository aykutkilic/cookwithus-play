// ------------------------------------------------------------------ pizzas share a dough
function pizza(id, name, level, blurb, toppings, bits, color = '#c8321e') {
  const ing = {
    flour: 1, yeast: 1, salt: 1, water: 1, oliveOil: 1, dough: 1, passata: 1, basil: 1,
  };
  const steps = [
    { id: 'flour', do: 'add', item: 'flour', into: 'bowl', title: 'Tip the flour into the bowl' },
    { id: 'yeast', do: 'add', item: 'yeast', into: 'bowl', after: ['flour'], title: 'Add the yeast' },
    { id: 'salt', do: 'season', item: 'salt', into: 'bowl', n: 2, after: ['flour'] },
    { id: 'water', do: 'pour', item: 'water', into: 'bowl', adds: 0.35, tint: false, after: ['yeast', 'salt'], title: 'Pour in lukewarm water' },
    { id: 'oil', do: 'pour', item: 'oliveOil', into: 'bowl', adds: 0.05, band: [0.3, 0.6], after: ['water'], title: 'A splash of olive oil' },
    { id: 'mix', do: 'stir', vessel: 'bowl', tool: 'hand', n: 3, makes: 'dough', after: ['oil'], title: 'Bring it together with your hand' },
    { id: 'knead', do: 'knead', item: 'dough', n: 12, after: ['mix'] },
    { id: 'rise', do: 'wait', dur: 60 * M, label: 'Let the dough rise (1 hour)', after: ['knead'] },
    { id: 'stretch', do: 'stretch', item: 'dough', n: 6, after: ['rise'], title: 'Stretch the base by hand' },
    { id: 'sauce', do: 'spread', item: 'dough', with: 'passata', tool: 'ladle', after: ['stretch'], title: 'Spread the tomato sauce' },
  ];
  let last = ['sauce'];
  for (const t of toppings) {
    ing[t.item] = t.qty || 1;
    let prep = null;
    if (t.wash) { steps.push({ id: `wash_${t.item}`, do: 'wash', item: t.item, n: 3 }); prep = `wash_${t.item}`; }
    if (t.prep) {
      steps.push({ id: `prep_${t.item}`, ...t.prep, item: t.item, after: prep ? [prep] : [] });
      prep = `prep_${t.item}`;
    }
    steps.push({ id: `top_${t.item}`, do: 'top', item: 'dough', with: t.item, n: t.n || 6, after: [...last, ...(prep ? [prep] : [])] });
    last = [`top_${t.item}`];
  }
  steps.push(
    { id: 'drizzle', do: 'season', item: 'oliveOil', target: 'dough', n: 2, after: last, title: 'Drizzle with olive oil' },
    { id: 'load', do: 'add', item: 'dough', into: 'tray', places: [{ item: 'dough', x: 0, y: 0 }], after: ['drizzle'], title: 'Slide the pizza onto the tray' },
    { id: 'bakeIn', do: 'bakeIn', vessel: 'tray', level: 3, ovens: ['electric', 'dome'], after: ['load'], title: 'Into the hottest oven' },
    { id: 'bake', do: 'wait', vessel: 'tray', dur: { electric: 10 * M, dome: 90 }, strict: true, label: 'Bake until bubbly and blistered', after: ['bakeIn'] },
    { id: 'bakeOut', do: 'bakeOut', vessel: 'tray', after: ['bake'] },
    { id: 'plate', do: 'add', item: 'dough', into: 'plates', after: ['bakeOut'], title: 'Onto the board' },
    { id: 'washBasil', do: 'wash', item: 'basil', n: 3 },
    { id: 'basil', do: 'garnish', into: 'plates', with: 'basil', n: 4, after: ['plate', 'washBasil'], title: 'A few fresh basil leaves' },
    { id: 'serve', do: 'serve', after: ['basil'] },
  );
  return {
    id, name, cuisine: 'italian', level, serves: 2, blurb,
    ing, ves: { bowl: 'bowl', tray: 'tray', plates: { kind: 'plate', name: 'board' } },
    dish: { base: 'pizzaBoard', main: 'pizza', color, bits, garnish: 'basil', steam: true },
    steps,
  };
}

